# PlatformIO pre-build script: bakes a reproducible build identity into each
# firmware image (R3/L3).
#
# The constant firmware string this replaces could not tell two materially
# different images apart. This script generates `EvBuildIdentity.h` in the
# environment's build directory (never in the source tree) carrying:
#
#   EV_BUILD_REVISION  short commit hash ("unknown" when unavailable)
#   EV_BUILD_DIRTY     1 when the tree has uncommitted changes (or when git
#                      metadata is unavailable at all - a build that cannot be
#                      shown clean never claims to be clean)
#
# The image variant (production/bench/bench-watchdog) is NOT detected here;
# it comes from the per-environment `EV_FIRMWARE_VARIANT` build define in
# `platformio.ini`, so a variant can never be misread from the tree.
#
# Reproducibility: the same source at the same commit with a clean tree
# generates byte-identical output on every rebuild. No timestamps, no paths,
# no environment. When git is missing (or fails), the build still succeeds
# with unknown/dirty rather than failing - missing metadata is honest, never
# fatal.
#
# Stale artifacts: the header is regenerated on every build into the build
# directory that `pio run -t clean` removes, so an identity can never outlive
# the tree it was generated from.

import subprocess
import os

Import("env")


def git_output(args):
    try:
        out = subprocess.check_output(
            ["git"] + args,
            cwd=env.subst("$PROJECT_DIR"),
            stderr=subprocess.DEVNULL,
            timeout=15,
        )
        return out.decode("utf-8", errors="replace").strip()
    except Exception:
        return ""


revision = git_output(["rev-parse", "--short=7", "HEAD"])
if not revision:
    revision = "unknown"

dirty = 1
status = git_output(["status", "--porcelain", "--untracked-files=no"])
if revision != "unknown" and status == "":
    # Porcelain with no output means no tracked modifications. Untracked
    # files are excluded on purpose: scratch captures and notes must not
    # dirty a build, while any tracked edit does.
    dirty = 0
if revision == "unknown":
    dirty = 1

generated_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
try:
    os.makedirs(generated_dir, exist_ok=True)
except Exception:
    pass

header_path = os.path.join(generated_dir, "EvBuildIdentity.h")
try:
    with open(header_path, "w") as header:
        header.write("#pragma once\n")
        header.write("// Generated by scripts/ev_build_identity.py - do not edit.\n")
        header.write('#define EV_BUILD_REVISION "%s"\n' % revision)
        header.write("#define EV_BUILD_DIRTY %d\n" % dirty)
except Exception as exc:
    print("ev_build_identity: warning: could not write %s (%s)" % (header_path, exc))
    revision = "unknown"
    dirty = 1

env.Append(CPPPATH=[generated_dir])
env.Append(CPPDEFINES=["EV_BUILD_IDENTITY_AVAILABLE=1"])

print("ev_build_identity: rev=%s dirty=%d" % (revision, dirty))
